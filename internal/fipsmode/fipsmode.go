// Package fipsmode is the single place that knows which Janus edition is
// running and whether the Go Cryptographic Module is operating in FIPS
// 140-3 mode.
//
// The FIPS edition is the same source tree built with
//
//	GOFIPS140=v1.0.0 go build -tags fips ./cmd/janus
//
// GOFIPS140 selects the frozen Go Cryptographic Module v1.0.0 (CMVP
// certificate #5247) and makes fips140=on the default; the fips tag only
// marks the edition. Everything else in Janus asks this package rather than
// carrying its own build tags, so the editions share every code path except
// the short list of features in Restricted().
package fipsmode

import (
	"crypto/fips140"
	"errors"
	"fmt"
)

// Edition names.
const (
	EditionDefault = "default"
	EditionFIPS    = "fips"
)

// ValidatedModuleVersion is the Go Cryptographic Module version that holds
// CMVP certificate #5247. The FIPS edition must link exactly this module.
const ValidatedModuleVersion = "v1.0.0"

// CMVPCertificate is the certificate the FIPS edition's module is covered by.
const CMVPCertificate = "#5247"

// Edition reports the compile-time edition: "fips" or "default".
func Edition() string { return edition }

// IsFIPSEdition reports whether this binary is the FIPS edition.
func IsFIPSEdition() bool { return edition == EditionFIPS }

// Active reports whether the Go Cryptographic Module is in FIPS 140-3 mode
// right now (GODEBUG fips140=on or only). Note that the default edition can
// be switched into this mode with GODEBUG, but it then runs an unvalidated
// module; only the FIPS edition combines this with ValidatedModuleVersion.
func Active() bool { return fips140.Enabled() }

// Enforced reports fips140=only: non-approved algorithms panic or error.
func Enforced() bool { return fips140.Enforced() }

// ModuleVersion is the linked Go Cryptographic Module version ("latest" for
// a build without GOFIPS140).
func ModuleVersion() string { return fips140.Version() }

// Feature identifies something the FIPS edition switches off because it
// needs a non-approved algorithm.
type Feature string

// Features restricted in the FIPS edition. Each entry is documented in
// docs/fips-edition.md; keep the two lists in step.
const (
	// FeatureTOTPSHA1 is TOTP with HMAC-SHA-1, the RFC 6238 default. The
	// FIPS edition enrolls HMAC-SHA-256 TOTP instead and refuses existing
	// SHA-1 enrollments.
	FeatureTOTPSHA1 Feature = "totp_sha1"
	// FeatureLegacyBcrypt is verification of bcrypt password and recovery
	// code hashes written by releases before PBKDF2. bcrypt is not an
	// approved algorithm; the FIPS edition does not compile it in.
	FeatureLegacyBcrypt Feature = "legacy_bcrypt"
	// FeaturePDFExport is report export as PDF. The PDF library hashes
	// fonts with SHA-1 and implements MD5/RC4 PDF encryption, so it is not
	// compiled into the FIPS edition.
	FeaturePDFExport Feature = "pdf_report_export"
	// FeatureEncryptedPDFRead is reading encrypted PDF attachments, which
	// needs MD5 and RC4.
	FeatureEncryptedPDFRead Feature = "encrypted_pdf_attachments"
	// FeatureDevAuth is the JANUS_DEV_AUTH evaluation sign-in bypass. It is
	// compiled out of the FIPS edition.
	FeatureDevAuth Feature = "dev_auth"
	// FeatureLDAPSkipVerify is LDAP over TLS without certificate checks.
	FeatureLDAPSkipVerify Feature = "ldap_skip_verify"
	// FeatureUntrustedTLS is connecting to an upstream whose TLS
	// certificate is not verified (per-upstream allow_untrusted_tls).
	FeatureUntrustedTLS Feature = "untrusted_tls"
)

// Restriction explains one restricted feature for APIs and the admin UI.
type Restriction struct {
	Feature     Feature `json:"feature"`
	Description string  `json:"description"`
	Alternative string  `json:"alternative"`
}

var restrictions = []Restriction{
	{FeatureTOTPSHA1, "Authenticator codes using HMAC-SHA-1 (the common default).", "New authenticator enrollments use HMAC-SHA-256; the authenticator app must support SHA-256."},
	{FeatureLegacyBcrypt, "Passwords and recovery codes still stored as bcrypt by releases before PBKDF2.", "An administrator resets the password; recovery codes are regenerated by setting up the authenticator again."},
	{FeaturePDFExport, "Report export as PDF.", "Export reports as Excel, CSV or JSON."},
	{FeatureEncryptedPDFRead, "Reading encrypted (password-protected) PDF attachments in chat.", "Attach an unencrypted copy of the PDF."},
	{FeatureDevAuth, "The JANUS_DEV_AUTH evaluation sign-in.", "Use local accounts or an identity provider."},
	{FeatureLDAPSkipVerify, "LDAP over TLS without certificate verification.", "Trust the directory's CA under Administration → Settings → Certificates."},
	{FeatureUntrustedTLS, "Upstreams whose TLS certificate is not verified (Allow untrusted certificate).", "Upload the upstream's CA under Administration → Settings → Certificates."},
}

// Restricted lists what the running edition switches off (empty in the
// default edition).
func Restricted() []Restriction {
	if !IsFIPSEdition() {
		return []Restriction{}
	}
	return append([]Restriction(nil), restrictions...)
}

// Allowed reports whether f is available in this edition.
func Allowed(f Feature) bool { return !IsFIPSEdition() }

// ErrUnavailable is returned (wrapped) by code paths a restricted feature
// would take.
var ErrUnavailable = errors.New("not available in the Janus FIPS edition")

// Unavailable returns an error naming f, or nil when f is allowed.
func Unavailable(f Feature) error {
	if Allowed(f) {
		return nil
	}
	return fmt.Errorf("%s: %w", f, ErrUnavailable)
}

// Status is the self-description exposed in logs, the admin API and the
// --fips-status command.
type Status struct {
	Edition         string        `json:"edition"`
	FIPS140Enabled  bool          `json:"fips140_enabled"`
	FIPS140Enforced bool          `json:"fips140_enforced"`
	ModuleVersion   string        `json:"module_version"`
	ValidatedModule bool          `json:"validated_module"`
	CMVPCertificate string        `json:"cmvp_certificate,omitempty"`
	Restricted      []Restriction `json:"restricted_features"`
}

// Current reports the running state.
func Current() Status {
	st := Status{
		Edition:         Edition(),
		FIPS140Enabled:  Active(),
		FIPS140Enforced: Enforced(),
		ModuleVersion:   ModuleVersion(),
		Restricted:      Restricted(),
	}
	st.ValidatedModule = st.ModuleVersion == ValidatedModuleVersion
	if st.ValidatedModule {
		st.CMVPCertificate = CMVPCertificate
	}
	return st
}

// CheckStartup refuses to run a FIPS edition binary that would not use the
// validated module in FIPS mode: one built without GOFIPS140=v1.0.0, or
// started with GODEBUG=fips140=off. The default edition always passes.
func CheckStartup() error { return check(Current()) }

func check(st Status) error {
	if st.Edition != EditionFIPS {
		return nil
	}
	if st.ModuleVersion != ValidatedModuleVersion {
		return fmt.Errorf("FIPS edition: linked Go Cryptographic Module is %q, not the validated %s (CMVP %s); rebuild with GOFIPS140=%s", st.ModuleVersion, ValidatedModuleVersion, CMVPCertificate, ValidatedModuleVersion)
	}
	if !st.FIPS140Enabled {
		return fmt.Errorf("FIPS edition: FIPS 140-3 mode is off (GODEBUG fips140=off?); refusing to start. Remove the override or use the default edition")
	}
	return nil
}
