/** Every catalog for a future locale must provide exactly these keys. */
type Catalog = typeof en;

type Leaves<T> = {
  [K in keyof T & string]: T[K] extends string ? K : `${K}.${Leaves<T[K]>}`;
}[keyof T & string];

/** A dotted path to one string in the catalog, checked at compile time. */
export type MessageKey = Leaves<Catalog>;

const catalogs: Record<string, Catalog> = { en };

let activeLocale = 'en';

/** Switches the active catalog; unknown locales fall back to English. */
export function setLocale(locale: string): void {
  activeLocale = locale in catalogs ? locale : 'en';
}

export function getLocale(): string {
  return activeLocale;
}

/**
 * Resolves a message key against the active catalog and substitutes
 * `{placeholder}` parameters. An unresolvable key returns the key itself —
 * visible and greppable, never a crash.
 */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let node: unknown = catalogs[activeLocale] ?? en;
  for (const part of key.split('.')) {
    if (node && typeof node === 'object' && part in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[part];
    } else {
      node = undefined;
      break;
    }
  }
  let message = typeof node === 'string' ? node : key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      message = message.split(`{${name}}`).join(String(value));
    }
  }
  return message;
}
